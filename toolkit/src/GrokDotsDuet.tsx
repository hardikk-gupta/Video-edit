// ---------- Hairline laptop, stepped frame by frame (see toolkit/src/vendor) ----------
const Laptop: React.FC<{at: number; w: number}> = ({at, w}) => {
  const host = useRef<HTMLDivElement>(null);
  const st = useRef<{f: Figure | null; sim: number}>({f: null, sim: 0});
  const lt = Math.max(0, useT() - at);
  useLayoutEffect(() => {
    const el = host.current;
    if (!el) return;
    const s = st.current;
    if (!s.f || lt < s.sim - 1e-6) {
      s.f?.destroy();
      __hlStep(el, 0, 0);
      s.f = laptop(el, {play: true, theme: 'dark', intensity: 0.9});
      s.sim = 0;
    }
    while (s.sim + 1 / 60 <= lt + 1e-9) {
      s.sim += 1 / 60;
      __hlStep(el, 1 / 60, s.sim * 1000);
    }
  });
  useEffect(() => () => st.current.f?.destroy(), []);
  return <div ref={host} style={{width: w, height: w * 0.8, '--hairline-plate': BG, '--hairline-hi': WHITE, '--hairline-edge': '#D2D2D6', '--hairline-mid': '#7C7C82', '--hairline-lo': '#3A3A3F', '--hairline-stroke': 1.6} as React.CSSProperties} />;
};

