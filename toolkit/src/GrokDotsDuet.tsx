// Content anchored in a cell: enters blur-to-sharp, leaves with a short blur.
const InCell: React.FC<{r: Rect; a: number; b: number; align?: 'center' | 'left'; children: (t: number) => React.ReactNode}> = ({r, a, b, align = 'center', children}) => {
  const t = useT();
  if (t < a || t >= b) return null;
  const pin = ease(t, a, 0.6);
  const pout = ease(t, b - 0.28, 0.28, IN_EXPO);
  return (
    <div
      style={{
        position: 'absolute', left: r.x + PAD, top: r.y + PAD, width: r.w - PAD * 2, height: r.h - PAD * 2,
        display: 'flex', flexDirection: 'column', justifyContent: 'center', alignItems: align === 'center' ? 'center' : 'flex-start',
        opacity: Math.min(1, pin * 1.4) * (1 - pout), transform: `translateY(${(1 - pin) * 24}px)`,
        filter: pin < 1 || pout > 0 ? `blur(${(1 - pin) * 10 + pout * 10}px)` : undefined,
      }}
    >
      {children(t)}
    </div>
  );
};

