// Visible between a and b, with blur-to-sharp in and a quick blur-out.
const Beat: React.FC<{a: number; b: number; children: (t: number) => React.ReactNode}> = ({a, b, children}) => {
  const t = useT();
  if (t < a - 0.01 || t >= b) return null;
  const pin = ease(t, a, 0.6);
  const pout = ease(t, b - 0.3, 0.3, IN_EXPO);
  return (
    <AbsoluteFill style={{height: GFX_H, opacity: Math.min(1, pin * 1.5) * (1 - pout), filter: pin < 1 || pout > 0 ? `blur(${(1 - pin) * 10 + pout * 12}px)` : undefined}}>
      {children(t)}
    </AbsoluteFill>
  );
};

