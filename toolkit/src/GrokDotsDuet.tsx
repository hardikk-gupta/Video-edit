// ---------- AI logos: a glimpse, then all of them ----------
const LogoGrid: React.FC<{t: number}> = ({t}) => {
  // 3.6 a slit of light appears; "jhalak" 4.92 it opens to a band; "AI" 6.12 the full grid; "closer" converges.
  const band = interpolate(t, [3.6, 4.0, 4.92, 5.5, 6.12, 6.7], [0, 6, 6, 170, 170, GFX_H], {...clamp, easing: IN_OUT});
  const conv = ease(t, 8.6, 1.4, IN_OUT);
  const cell = 255;
  return (
    <AbsoluteFill style={{height: GFX_H}}>
      <div style={{position: 'absolute', left: 0, right: 0, top: GFX_CY - band / 2, height: band, overflow: 'hidden'}}>
        <div style={{position: 'absolute', left: 0, right: 0, top: band / 2 - GFX_CY, height: GFX_H}}>
          {LOGOS.map((l, i) => {
            const col = i % 3;
            const row = Math.floor(i / 3);
            const x = 540 + (col - 1) * cell * 1.25;
            const y = GFX_CY - 18 + (row - 1) * cell * 0.9;
            const p = ease(t, 6.0 + i * 0.07, 0.6);
            // Before the grid lands, logos drift sideways inside the band (a glimpse).
            const glimpse = t < 6.12;
            const gx = glimpse ? 540 + (((t * 160 + i * 240) % 1300) - 650) : x;
            const gy = glimpse ? GFX_CY : y;
            const cx = gx + (540 - gx) * conv;
            const cy = gy + (GFX_CY - gy) * conv;
            return (
              <div key={l} style={{position: 'absolute', left: cx, top: cy, transform: `translate(-50%, -50%) scale(${(glimpse ? 0.8 : 0.85 + 0.15 * p) * (1 - conv * 0.7)})`, opacity: (glimpse ? 0.55 : 1) * (1 - conv), display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 16}}>
                <Logo name={l} h={l === 'grok' ? 78 : 124} />
                <div style={{fontFamily: SANS, fontSize: 30, color: GRAY, opacity: glimpse ? 0 : p}}>{LOGO_NAMES[l]}</div>
              </div>
            );
          })}
        </div>
      </div>
      {band > 0 && band < GFX_H - 1 && <div style={{position: 'absolute', left: 0, right: 0, top: GFX_CY - band / 2, height: band, boxShadow: '0 0 60px rgba(255,255,255,.18)', borderTop: '1px solid rgba(255,255,255,.35)', borderBottom: '1px solid rgba(255,255,255,.35)'}} />}
    </AbsoluteFill>
  );
};

