const shotIndex = (t: number) => {
  let i = 0;
  while (i + 1 < SHOTS.length && t >= SHOTS[i + 1].at) i++;
  return i;
};

const camera = (s: Shot, t: number) => {
  let k = 0;
  while (k + 1 < s.views.length && t >= s.views[k + 1][0]) k++;
  const cur = s.views[k];
  const prev = k ? s.views[k - 1] : cur;
  const p = k ? ease(t, cur[0], 0.75, IN_OUT) : 1;
  const drift = 1 - Math.max(0, t - Math.max(cur[0], s.at)) * 0.012; // never fully still
  return {cx: mix(prev[1], cur[1], p), cy: mix(prev[2], cur[2], p), vw: mix(prev[3], cur[3], p) * drift};
};

const ShotLayer: React.FC<{s: Shot; t: number; cw: number; ch: number; opacity: number}> = ({s, t, cw, ch, opacity}) => {
  const {cx, cy, vw} = camera(s, t);
  const k = cw / vw;
  const tx = cw / 2 - cx * k;
  const ty = ch / 2 - cy * k;
  const box = s.boxes?.find(([a, b]) => t >= a && t < b);
  return (
    <AbsoluteFill style={{opacity, background: s.bg ?? '#0E0E0E', overflow: 'hidden'}}>
      {s.custom ? (
        s.custom(t)
      ) : (
        <div style={{position: 'absolute', left: 0, top: 0, width: s.iw, height: s.ih, transformOrigin: '0 0', transform: `translate(${tx}px, ${ty}px) scale(${k})`}}>
          <Img src={staticFile(s.src!)} style={{width: s.iw, height: s.ih, display: 'block'}} />
          {s.overlay?.(t)}
        </div>
      )}
      {box && <Highlight t={t} box={box} k={k} tx={tx} ty={ty} />}
    </AbsoluteFill>
  );
};

const Highlight: React.FC<{t: number; box: Box; k: number; tx: number; ty: number}> = ({t, box, k, tx, ty}) => {
  const [a, , x, y, w, h] = box;
  const p = ease(t, a, 0.45);
  const pad = 14;
  return (
    <div
      style={{
        position: 'absolute',
        left: tx + x * k - pad,
        top: ty + y * k - pad,
        width: w * k + pad * 2,
        height: h * k + pad * 2,
        border: `3px solid ${WHITE}`,
        borderRadius: 14,
        boxShadow: `0 0 0 4000px rgba(0,0,0,${0.5 * p})`,
        opacity: p,
        transform: `scale(${1.06 - 0.06 * p})`,
      }}
    />
  );
};

// The card: full-frame for the opening jinn, then it settles into the top panel.
const Card = () => {
  const t = useT();
  const m = ease(t, 1.5, 0.75, IN_OUT);
  const x = mix(0, CARD.x, m);
  const y = mix(0, CARD.y, m);
  const w = mix(GDD_W, CARD.w, m);
  const h = mix(GDD_H, CARD.h, m);
  const r = mix(0, 30, m);
  const i = shotIndex(t);
  const cur = SHOTS[i];
  const prev = i ? SHOTS[i - 1] : null;
  const xf = prev ? ease(t, cur.at, 0.3, IN_OUT) : 1;
  const out = ease(t, END - 0.5, 0.5, IN_OUT);
  return (
    <div style={{position: 'absolute', left: x, top: y, width: w, height: h, borderRadius: r, overflow: 'hidden', background: '#0E0E0E', boxShadow: m > 0 ? `0 0 0 1px rgba(255,255,255,${0.1 * m})` : undefined, opacity: 1 - out}}>
      {prev && xf < 1 && <ShotLayer s={prev} t={t} cw={w} ch={h} opacity={1} />}
      <div style={{position: 'absolute', inset: 0, filter: xf < 1 ? `blur(${(1 - xf) * 10}px)` : undefined}}>
        <ShotLayer s={cur} t={t} cw={w} ch={h} opacity={xf} />
      </div>
    </div>
  );
};

