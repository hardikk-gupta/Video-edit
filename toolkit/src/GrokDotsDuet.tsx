// ---------- Hairline figures, stepped frame by frame (toolkit/src/vendor) ----------
const FIGS = {branches, hub, laptop, phosphor, riffle, settle, slow, terminal};
const Fig: React.FC<{fig: keyof typeof FIGS; at: number; w: number; intensity?: number}> = ({fig, at, w, intensity = 0.8}) => {
  const host = useRef<HTMLDivElement>(null);
  const st = useRef<{f: Figure | null; sim: number}>({f: null, sim: 0});
  const lt = Math.max(0, useT() - at);
  useLayoutEffect(() => {
    const el = host.current;
    if (!el) return;
    const s = st.current;
    if (!s.f || lt < s.sim - 1e-6) {
      s.f?.destroy();
      __hlStep(el, 0, 0);
      s.f = FIGS[fig](el, {play: true, theme: 'dark', intensity});
      s.sim = 0;
    }
    while (s.sim + 1 / 60 <= lt + 1e-9) {
      s.sim += 1 / 60;
      __hlStep(el, 1 / 60, s.sim * 1000);
    }
  });
  useEffect(() => () => st.current.f?.destroy(), []);
  return <div ref={host} style={{width: w, height: w * 0.8, flex: 'none', '--hairline-plate': BG, '--hairline-hi': WHITE, '--hairline-edge': '#D8D8DC', '--hairline-mid': '#85858B', '--hairline-lo': '#3E3E43', '--hairline-stroke': 1.7} as React.CSSProperties} />;
};

